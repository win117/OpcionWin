import { Router } from 'express';
import { mercado as rutas } from '../schemas';
import controller from '../controllers/mercado.controller';
import { forRepository as empresas } from '../controllers/empresas.controller';
import { forRepository as contratos } from '../controllers/contratos.controller';
import { forRepository as noticias } from '../controllers/noticias.controller';
import { registrar } from './registrar';

export default ({ factory, integraciones, universo, tasa, eventos } = {}) => {
  const router = Router(), c = controller(factory, integraciones, universo, { tasa, eventos });
  router.base = '/mercado';
  const r = (definicion, manejador) => registrar(router, definicion, manejador);
  r(rutas.empresas, empresas(factory).list);
  r(rutas.estado, c.estado);
  r(rutas.movimientos, c.movimientos);
  r(rutas.mapa, c.mapa);
  r(rutas.ficha, c.ficha);
  r(rutas.tasa, c.tasa);
  r(rutas.eventos, c.eventos);
  r(rutas.panorama, c.panorama);
  r(rutas.cotizacionEnVivo, c.liveQuote);
  r(rutas.cotizaciones, c.quotes);
  r(rutas.historicos, c.history);
  r(rutas.fundamentales, c.fundamentals);
  r(rutas.institucional, c.institutional);
  r(rutas.cadena, c.chain);
  r(rutas.resumenOpciones, c.resumenOpciones);
  r(rutas.velasOpcion, c.velasOpcion);
  r(rutas.contratos, contratos(factory).list);
  r(rutas.snapshot, c.snapshot);
  r(rutas.contrato, contratos(factory).get);
  r(rutas.noticias, noticias(factory).list);
  return router;
};
